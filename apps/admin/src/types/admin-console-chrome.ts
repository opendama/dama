function chromeFieldReady(key: string, v: unknown): boolean {
  if (typeof v !== "string" || v.length === 0) return false;
  if (key.endsWith("_separator") || key.endsWith("_joiner") || key.endsWith("_space")) {
    return true;
  }
  return v.trim().length > 0;
}

function sectionReady(sec: AdminConsoleSection | undefined, keys: string[]): boolean {
  if (!sec) return false;
  return keys.every((k) => chromeFieldReady(k, sec[k]));
}

/** Fail closed: every admin console chrome section must be present from the database. */
export function isAdminConsoleChromeReady(
  chrome: AdminConsoleChrome | null | undefined,
): chrome is Required<AdminConsoleChrome> {
  if (!chrome) return false;
  if (typeof chrome.source !== "string" || chrome.source.trim().length === 0) return false;
  if (
    typeof chrome.admin_console_chrome_unavailable !== "string" ||
    chrome.admin_console_chrome_unavailable.trim().length === 0
  ) {
    return false;
  }
  return (Object.keys(SECTION_KEYS) as (keyof typeof SECTION_KEYS)[]).every((section) =>
    sectionReady(chrome[section], SECTION_KEYS[section]),
  );
}
